"""Run the full EDA pass on both datasets and write results/eda_report.md.

    python3 run_eda.py

Reproduces every number quoted in the blog post. Also writes one CSV per
dataset per report under results/ so the numbers are auditable without
re-running anything.
"""

from __future__ import annotations

import os

import pandas as pd

from eda_portfolio import datasets, eda

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(HERE, "results")

DATASETS = {
    "wine": datasets.load_wine_dataset,
    "diabetes": datasets.load_diabetes_dataset,
}


def run_one(name: str, loader) -> str:
    df, target = loader()
    stats = eda.summary_stats(df)
    missing = eda.missing_report(df)
    outliers = eda.outlier_report(df)
    correlations = eda.correlation_report(df)

    stats.to_csv(os.path.join(RESULTS_DIR, f"{name}_summary_stats.csv"))
    outliers.to_csv(os.path.join(RESULTS_DIR, f"{name}_outliers.csv"))
    correlations.to_csv(os.path.join(RESULTS_DIR, f"{name}_top_correlations.csv"), index=False)

    lines = [f"## {name}", "", f"- rows: {len(df)}, columns: {len(df.columns)}, target: `{target}`"]
    lines.append(f"- missing values: {int(df.isna().sum().sum())}")
    if not missing.empty:
        missing.to_csv(os.path.join(RESULTS_DIR, f"{name}_missing.csv"))
        lines.append(f"  - by column:\n{missing.to_markdown()}")

    total_outliers = int(outliers["outliers"].sum())
    worst = outliers.iloc[0]
    lines.append(
        f"- outliers (Tukey IQR, k=1.5): {total_outliers} total across "
        f"{len(outliers)} numeric columns; worst is `{outliers.index[0]}` with "
        f"{int(worst['outliers'])} ({worst['outlier_pct']}%)"
    )

    if not pd.api.types.is_numeric_dtype(df[target]):
        balance = eda.class_balance(df[target])
        balance.to_csv(os.path.join(RESULTS_DIR, f"{name}_class_balance.csv"))
        lines.append(f"- class balance:\n{balance.to_markdown()}")

    lines.append(f"- top correlated feature pairs:\n{correlations.to_markdown(index=False)}")
    lines.append("")
    section = "\n".join(lines)
    print(section)
    return section


def main() -> None:
    os.makedirs(RESULTS_DIR, exist_ok=True)
    sections = [run_one(name, loader) for name, loader in DATASETS.items()]
    report = "# EDA report\n\nGenerated by `python3 run_eda.py`.\n\n" + "\n".join(sections)
    with open(os.path.join(RESULTS_DIR, "eda_report.md"), "w") as f:
        f.write(report)


if __name__ == "__main__":
    main()
